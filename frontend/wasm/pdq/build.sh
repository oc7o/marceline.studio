#!/usr/bin/env bash
# Compile Meta's PDQ hasher to WebAssembly with Emscripten, inside Docker.
#
# No local emcc needed: the pinned emscripten/emsdk image below is the only
# toolchain. Re-runnable and reproducible - the same sources produce the same
# bytes, and the script prints the sha256 of the output so a rebuild can be
# compared against the committed artifact.
#
#   ./frontend/wasm/pdq/build.sh
#
# The output is committed (frontend/src/wasm/pdq-wasm.js), so `npm ci` users
# never need Docker. See README.md.
set -euo pipefail

# Pinned toolchain. Bump deliberately: a different Emscripten/LLVM can change
# floating-point code generation, and with it the hashes (see README).
IMAGE="emscripten/emsdk:4.0.9"

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
out_dir="$(cd "$here/../../src" && pwd)/wasm"
out_name="pdq-wasm.js"

mkdir -p "$out_dir"

# -ffp-contract=off: without it the compiler may fuse a*b+c into a single FMA
#   with only one rounding step. PDQ's DCT and box filters are long float sums,
#   so a fused multiply-add changes low bits, which flips hash bits near the
#   median threshold. The server's pdqhash is built without FMA contraction,
#   so the WASM build must be too - this is the flag that makes parity hold.
# -fno-fast-math / no -ffast-math: reassociation would break parity as well.
# -O3: the hasher runs per frame in a Worker.
EMCC_FLAGS=(
  -O3
  -std=c++17
  -ffp-contract=off
  -fno-fast-math
  -I vendor
  --no-entry
  -s MODULARIZE=1
  -s EXPORT_ES6=1
  -s EXPORT_NAME=createPdqModule
  -s SINGLE_FILE=1
  -s ENVIRONMENT=web,worker,node
  -s ALLOW_MEMORY_GROWTH=1
  -s STACK_SIZE=1048576
  -s FILESYSTEM=0
  -s INVOKE_RUN=0
  -s ASSERTIONS=0
  -s EXPORTED_FUNCTIONS=_marceline_pdq_dihedral_rgb,_marceline_pdq_dihedral_luma,_marceline_pdq_abi_version,_malloc,_free
  -s EXPORTED_RUNTIME_METHODS=HEAPU8
)

SOURCES=(
  src/pdq_wasm.cpp
  vendor/pdq/cpp/hashing/pdqhashing.cpp
  vendor/pdq/cpp/hashing/torben.cpp
  vendor/pdq/cpp/downscaling/downscaling.cpp
)

echo "Building $out_name with $IMAGE"
docker run --rm \
  --network none \
  -u "$(id -u):$(id -g)" \
  -e EM_CACHE=/tmp/emcache \
  -v "$here:/src" \
  -v "$out_dir:/out" \
  -w /src \
  "$IMAGE" \
  emcc "${EMCC_FLAGS[@]}" "${SOURCES[@]}" -o "/out/$out_name"

# Mark the artifact as generated for humans and review tools. The banner is
# prepended after the build so emcc never sees it. (eslint skips the whole
# src/wasm folder; see frontend/eslint.config.js.)
banner="$(mktemp)"
trap 'rm -f "$banner"' EXIT
{
  echo "// @generated by frontend/wasm/pdq/build.sh - do not edit."
  echo "// Meta PDQ (BSD-3) compiled with $IMAGE; see frontend/wasm/pdq/README.md."
  cat "$out_dir/$out_name"
} > "$banner"
mv "$banner" "$out_dir/$out_name"
trap - EXIT
# mktemp and the container's umask would otherwise leave the committed file 0600.
chmod 644 "$out_dir/$out_name"

echo
echo "wrote $out_dir/$out_name"
ls -l "$out_dir/$out_name" | awk '{print "size:", $5, "bytes"}'
sha256sum "$out_dir/$out_name"

"""Write the photo-collection parity fixture (issue #116, ADR 0053). Run by hand.

    cd backend && uv run python -m matching.tests.generate_photo_fixtures

The browser hashes a photo set with the same recipe the CLI does — the image at its own
resolution, RGB, PDQ, eight orientations — and builds the same document. Only the **decoder**
differs, which is what `browser-rgb-pdq-v0` records and what `make browser-parity
PARITY_ARGS="--photos"` measures in a real browser. Everything else has to be identical bit for
bit, and that is what this fixture pins:

- `matching/tests/test_photo_fixtures.py` asserts Python still produces these hashes from these
  pixels, so a change on the server side shows up here;
- `frontend/src/lib/photoFingerprint.test.ts` reads the same file and asserts the browser code,
  fed the same pixels, produces the same eight hashes per image, the same quality, the same
  `image_count` and above all the same **collection digest**.

Synthetic images only — gradients, seeded noise, a checkerboard, a near-uniform picture below the
quality floor and an odd non-square size. No real or pirated media, ever, as everywhere else in
this repository. The raw RGB of each image is stored beside its hashes so the browser test needs
no image decoder: the decoder gap is the one thing a unit test cannot measure.
"""

import base64
import hashlib
import json
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

from matching.fingerprint import fingerprint_photos, to_json

FIXTURES = Path(__file__).parent / "fixtures" / "photos"


def _images() -> list[tuple[str, Image.Image]]:
    """The pictures, named as they are written to disk (sorted path order = this order)."""
    rows, columns = np.mgrid[0:24, 0:32]
    gradient = np.stack(
        [(rows * 10) % 256, (columns * 8) % 256, ((rows + columns) * 6) % 256], axis=-1
    ).astype(np.uint8)

    generator = np.random.default_rng(20260918)
    noise = generator.integers(0, 256, size=(29, 17, 3), dtype=np.uint8)

    checker = np.zeros((40, 40, 3), dtype=np.uint8)
    checker[::8, :, :] = 255
    checker[:, ::8, :] = 200

    # Featureless on purpose: below MIN_QUALITY, so it keeps its ordinal and contributes no hashes.
    blank = np.full((20, 20, 3), 17, dtype=np.uint8)

    return [
        ("01-gradient.png", Image.fromarray(gradient, "RGB")),
        ("02-noise.png", Image.fromarray(noise, "RGB")),
        ("03-checker.png", Image.fromarray(checker, "RGB")),
        ("04-blank.png", Image.fromarray(blank, "RGB")),
    ]


def main() -> None:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as directory:
        folder = Path(directory)
        written: list[Path] = []
        for name, image in _images():
            path = folder / name
            # PNG: lossless, so the pixels a browser decodes are the pixels Pillow decoded, and
            # this fixture is about everything *except* the decoder.
            image.save(path, format="PNG", optimize=False)
            written.append(path)
        fingerprint = fingerprint_photos(written, title="Synthetic set", creators=["Alias"])
        images = []
        for index, path in enumerate(sorted(written)):
            data = path.read_bytes()
            with Image.open(path) as opened:
                pixels = np.asarray(opened.convert("RGB"), dtype=np.uint8)
            images.append(
                {
                    "frame_index": index,
                    "sha256": hashlib.sha256(data).hexdigest(),
                    "size": len(data),
                    "width": int(pixels.shape[1]),
                    "height": int(pixels.shape[0]),
                    "rgb_base64": base64.b64encode(pixels.tobytes()).decode("ascii"),
                }
            )
    document = to_json(fingerprint)
    # The machine that generated it is not part of the contract.
    document["client"] = {"tool": "generate_photo_fixtures"}
    payload = {
        "note": (
            "Synthetic images and the document `fingerprint_photos` writes for them. "
            "Generated by matching/tests/generate_photo_fixtures.py; see ADR 0053."
        ),
        "images": images,
        "document": document,
    }
    (FIXTURES / "collection.json").write_text(json.dumps(payload, indent=2) + "\n", "utf-8")
    print(f"wrote {FIXTURES / 'collection.json'} ({len(images)} images)")


if __name__ == "__main__":
    main()
